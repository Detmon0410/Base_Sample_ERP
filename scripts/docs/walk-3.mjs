import { open, login, shot, state, URL_BASE } from "./walk-lib.mjs";
const { browser, page } = await open();
await login(page, "sale@gmail.com", "sale");
await page.goto(state().qtUrl);
await page.waitForSelector("text=Confirm QT");
await page.getByRole("button", { name: "Confirm QT" }).click();
await page.waitForTimeout(800);
await page.locator("[role=alertdialog] button, [role=dialog] button").filter({ hasText: /^Confirm$/ }).click();
await page.waitForTimeout(3800);
await page.evaluate(() => window.scrollTo(0, 0));
await shot(page, "09-qt-confirmed");
console.log((await page.locator("body").innerText()).slice(0, 900));
console.log("LINKS:", await page.locator("a").evaluateAll((a) => a.map((x) => x.innerText + "=" + x.getAttribute("href")).filter((s) => /order/i.test(s)).join(" | ")));
await shot(page, "10-orders-list-after");
