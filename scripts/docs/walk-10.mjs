import { open, login, shot, URL_BASE } from "./walk-lib.mjs";
const { browser, page } = await open();
await login(page, "admin@gmail.com", "admin");
await page.goto(URL_BASE + "accounting");
await page.waitForTimeout(1200);
await page.getByRole("button", { name: "Issue invoice" }).click();
await page.waitForTimeout(1200);
await shot(page, "26-issue-invoice-dialog");
console.log(await page.evaluate(() => [...document.querySelectorAll("[role=dialog] input,[role=dialog] select,[role=dialog] textarea,[role=dialog] button")].map((e) => `${e.tagName} name=${e.name} text=${e.innerText} val=${e.value}`).join("\n")));
console.log(await page.locator("[role=dialog]").innerText());
await browser.close();
