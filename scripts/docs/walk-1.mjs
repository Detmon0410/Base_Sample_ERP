import { open, login, shot, state, URL_BASE, DIR } from "./walk-lib.mjs";
const { browser, page } = await open();
await login(page, "sale@gmail.com", "sale", "01-login");
await shot(page, "02-dashboard");
await page.goto(URL_BASE + "sale/quotations");
await shot(page, "03-qt-list");
await page.goto(URL_BASE + "sale/quotations/new");
await page.waitForTimeout(800);
await shot(page, "04-qt-new-empty");
await page.fill('input[name="qtNumber"]', "QT-2026-020");
await page.fill('input[name="qtDate"]', "2026-10-21");
await page.selectOption('select[name="customerId"]', { index: 1 });
await page.selectOption('select[name="lines.0.productId"]', { index: 2 });
await page.fill('input[name="lines.0.quantity"]', "2");
await page.fill('input[name="customerPoNumber"]', "PO-2026-0008");
await page.fill('input[name="customerPoDate"]', "2026-10-21");
await shot(page, "05-qt-filled");
await page.getByRole("button", { name: "Save" }).click();
await page.waitForSelector("text=Confirm QT");
await page.mouse.move(0, 0);
await page.waitForTimeout(3500);
await shot(page, "06-qt-saved");
state({ qtUrl: page.url() });
// upload the customer PO
await page.locator('input[type="file"]').first().setInputFiles(DIR + "customer-po.pdf");
await page.waitForTimeout(2000);
await page.locator("text=Files").first().scrollIntoViewIfNeeded();
await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
await shot(page, "07-qt-po-uploaded");
console.log((await page.locator("body").innerText()).slice(-900));
await browser.close();
